class TestNoUndefinedFunctions(unittest.TestCase):
    """Verify all payloads have no undefined function calls"""

    def setUp(self):
        self.validator = VBSSyntaxValidator()
        self.gen = PayloadGenerator()
        self.test_command = "cmd /c echo test"

    def _check_no_undefined_functions(self, payload: str, test_name: str):
        """Helper to check payload has no undefined functions"""
        is_valid, errors = self.validator.validate(payload)
        undefined_errors = [e for e in errors if e.error_type == "UNDEFINED_FUNCTION"]
        self.assertEqual(
            len(undefined_errors), 0,
            f"{test_name}: Found undefined functions: "
            f"{[e.message for e in undefined_errors]}\n\nPayload:\n{payload}"
        )

    def test_all_techniques_no_undefined_functions(self):
        """Test all techniques have no undefined functions"""
        for technique in self.gen.list_techniques():
            payload = self.gen.generate(self.test_command, technique=technique)
            self._check_no_undefined_functions(payload, f"Technique: {technique}")


