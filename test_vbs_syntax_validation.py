class TestVBSSyntaxValidator(unittest.TestCase):
    """Test the VBS syntax validator itself"""

    def setUp(self):
        self.validator = VBSSyntaxValidator()

    def test_valid_simple_code(self):
        """Test validation of simple valid VBS code"""
        code = """
Dim shell
Set shell = CreateObject("WScript.Shell")
shell.Run "cmd /c test", 0, False
"""
        is_valid, errors = self.validator.validate(code)
        self.assertTrue(is_valid, f"Should be valid. Errors: {errors}")

    def test_undefined_function_detection(self):
        """Test detection of undefined functions"""
        code = """
Dim result
result = UndefinedFunction("test")
"""
        is_valid, errors = self.validator.validate(code)
        self.assertFalse(is_valid, "Should detect undefined function")
        self.assertTrue(any(e.error_type == "UNDEFINED_FUNCTION" for e in errors))

    def test_undefined_variable_in_context(self):
        """Test that declared variables are recognized"""
        code = """
Dim myVar
myVar = "test"
"""
        is_valid, errors = self.validator.validate(code)
        self.assertTrue(is_valid, f"Should recognize declared variables. Errors: {errors}")

    def test_mismatched_if_end(self):
        """Test detection of mismatched If/End If"""
        code = """
If True Then
    Dim x
    x = 1
End If
End If
"""
        is_valid, errors = self.validator.validate(code)
        self.assertFalse(is_valid, "Should detect mismatched End If")

    def test_unclosed_function(self):
        """Test detection of unclosed Function block"""
        code = """
Function MyFunc()
    Dim x
    x = 1
"""
        is_valid, errors = self.validator.validate(code)
        self.assertFalse(is_valid, "Should detect unclosed function")
        self.assertTrue(any(e.error_type == "UNCLOSED_BLOCK" for e in errors))

    def test_for_loop_balanced(self):
        """Test balanced For/Next loops"""
        code = """
Dim i
For i = 1 To 10
    Dim x
    x = i
Next
"""
        is_valid, errors = self.validator.validate(code)
        self.assertTrue(is_valid, f"Should have balanced For/Next. Errors: {errors}")

    def test_builtin_functions_allowed(self):
        """Test that built-in functions are recognized"""
        code = """
Dim s
s = LCase("TEST")
s = UCase(s)
s = Len(s)
s = Mid(s, 1, 1)
"""
        is_valid, errors = self.validator.validate(code)
        self.assertTrue(is_valid, f"Should allow built-in functions. Errors: {errors}")


